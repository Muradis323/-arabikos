"""Compile the checked transcription and glossary; refuse incomplete word coverage."""
from pathlib import Path
import json,re,unicodedata
root=Path(__file__).resolve().parents[1]
def normal(w):return re.sub(r'[^\u0621-\u063a\u0641-\u064a]','',unicodedata.normalize('NFKC',w).replace('ٱ','ا'))
gloss={}
for line in (root/'content/adhkar-glossary.tsv').read_text().splitlines():
 key,ru=line.split('\t',1)
 if key in gloss:raise ValueError('Duplicate glossary key '+key)
 gloss[key]=ru
blocks=[]
for n,line in enumerate((root/'content/adhkar-opening.txt').read_text().splitlines()):
 page,kind,text=line.split('|',2);tokens=[];start=0
 for match in re.finditer(r'[\u0621-\u063a\u0640-\u065f\u0670-\u0671]+',text):
  if match.start()>start:tokens.append({'ar':text[start:match.start()]})
  ar=match.group();key=normal(ar)
  if key not in gloss:raise ValueError('Untranslated word '+ar+' / '+key)
  tokens.append({'ar':ar,'ru':gloss[key]});start=match.end()
 if start<len(text):tokens.append({'ar':text[start:]})
 start_page,*rest=page.split('-');end=int(rest[0]) if rest else int(start_page)
 assert ''.join(t['ar'] for t in tokens)==text
 assert text.count('«')==text.count('»'),text
 assert text.count('﴿')==text.count('﴾'),text
 blocks.append({'id':f'adhkar-{n+1}','page':int(start_page),'endPage':end,'kind':kind,'tokens':tokens})
book={'id':'adhkar-chapter1-v2','title':'الذِّكْرُ وَالدُّعَاءُ فِي ضَوْءِ الْكِتَابِ وَالسُّنَّةِ','pages':'15–19','blocks':blocks}
(root/'lib/adhkar-book.ts').write_text('// Generated by scripts/build-adhkar.py from the checked uploaded PDF transcription.\nexport const adhkarBook='+json.dumps(book,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(blocks),'complete blocks,',sum('ru' in t for b in blocks for t in b['tokens']),'translated word occurrences')
